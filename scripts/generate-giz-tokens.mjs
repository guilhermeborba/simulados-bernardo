import { readFile, writeFile } from 'node:fs/promises';
const source = JSON.parse(await readFile(new URL('../giz-handoff/tokens/tokens.json', import.meta.url), 'utf8'));
function colorDeclarations(mode) {
  return Object.entries(source.color[mode]).filter(([key, value]) => !key.startsWith('_') && value?.value).map(([key, value]) => `  --${key}: ${value.value};`);
}
const lines = ['/* Generated by scripts/generate-giz-tokens.mjs from tokens.json. Do not edit. */', ':root {', ...colorDeclarations('light')];
for (const [key, value] of Object.entries(source.radius)) lines.push(`  --r-${key}: ${value}px;`);
for (const [key, value] of Object.entries(source.shadow)) lines.push(`  --${key === 'sheet' ? 'e-sheet' : key}: ${value};`);
for (const value of source.space) lines.push(`  --s-${value / 4}: ${value}px;`);
lines.push(`  --touch-min: ${source.size['touch-min']}px; --touch-kids: ${source.size['touch-kids']}px; color-scheme: light;`);
for (const [key, value] of Object.entries(source.type)) {
  if (key.startsWith('_')) continue;
  lines.push(`  --text-${key}: ${value.mobile[0] / 16}rem; --text-${key}-line: ${value.mobile[1] / 16}rem;`);
}
const sizes = {
  touch: source.size['touch-kids'], option: source.size['option-min-height'], chip: source.size['chip-min-height'],
  nav: source.size['bottom-nav-height'], sidebar: source.breakpoint['sidebar-desktop'], 'sidebar-tablet': source.breakpoint['sidebar-tablet'],
  content: source.breakpoint['container-max'], 'avatar-sm': source.size.avatar[0], 'avatar-md': source.size.avatar[1], 'avatar-lg': source.size.avatar[2],
  'icon-sm': source.size.icon[0], 'icon-md': source.size.icon[1], 'icon-lg': source.size.icon[2],
};
for (const [key, value] of Object.entries(sizes)) lines.push(`  --size-${key}: ${value}px;`);
for (const [key, value] of Object.entries(source.layout)) {
  if (!key.startsWith('_')) lines.push(`  --size-${key}: ${value}px;`);
}
lines.push(`  --border-thin: ${source.border.thin}px; --border: ${source.border.default}px; --focus-ring: ${source.border.focus}px; --overlay: ${source.overlay.value};`);
lines.push('  --motion-fast: '+source.motion.rapido+'; --motion-standard: '+source.motion.padrao+';');
lines.push('  --font-d: var(--font-fredoka), '+source.font.display.fallback+'; --font-b: var(--font-nunito), '+source.font.body.fallback+';');
for (const [track, value] of Object.entries(source.color.trilha)) lines.push(`  --trail-${track}: ${value.destaque}; --trail-${track}-soft: ${value['fundo-suave']};`);
lines.push('  --track-accent: var(--trail-kids);');
lines.push('}');
for (const track of Object.keys(source.color.trilha)) lines.push(`:root[data-track="${track}"] { --track-accent: var(--trail-${track}); }`);
lines.push('@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {', ...colorDeclarations('dark'), '  color-scheme: dark;', '} }');
lines.push(':root[data-theme="dark"] {', ...colorDeclarations('dark'), '  color-scheme: dark;', '}');
lines.push(`@media (min-width: ${source.breakpoint['desktop-min']}px) { :root {`);
for (const [key, value] of Object.entries(source.type)) {
  if (key.startsWith('_')) continue;
  lines.push(`  --text-${key}: ${value.desktop[0] / 16}rem; --text-${key}-line: ${value.desktop[1] / 16}rem;`);
}
lines.push('} }');
lines.push('@media (prefers-reduced-motion: reduce) { *, *::before, *::after { transition: none !important; animation: none !important; scroll-behavior: auto !important; } }');
await writeFile(new URL('../app/giz-tokens.css', import.meta.url), lines.join('\n')+'\n');
// Typed tokens for metadata and validation, sharing the native source of truth.
await writeFile(new URL('../lib/gizTokens.generated.ts', import.meta.url), '// Generated; run node scripts/generate-giz-tokens.mjs.\nexport const gizTokens = '+JSON.stringify(source,null,2)+' as const;\n');
